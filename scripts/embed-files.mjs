// Copies db/schema.sql and mapping/attributes.csv into a TypeScript module, so the app on Vercel
// always has them (files read from disk at runtime are not always included in the server bundle).
import fs from "node:fs";

const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const out = `// Generated by scripts/embed-files.mjs from db/schema.sql and mapping/attributes.csv. Do not edit.
export const SCHEMA_SQL = ${JSON.stringify(read("db/schema.sql"))};
export const MAPPING_CSV = ${JSON.stringify(read("mapping/attributes.csv"))};
`;
fs.writeFileSync(new URL("../src/generated/files.ts", import.meta.url), out);
